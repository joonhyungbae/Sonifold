"""
Full experiment: for each (manifold × audio × mapping strategy) measure topology metrics -> results.csv.
9 paper meshes, 7 audio, 3 strategies = 189 conditions.

The mesh list is pinned to PAPER_MESHES rather than globbed from data/eigen/*.npz.
data/eigen also holds the extended meshes used by the spectral-entropy analysis
(ellipsoid_112, genus7, torus_Rr2, ...); globbing the directory would silently
change the size of the results table as those meshes come and go.

Use --all to run over every eigenbasis present instead (writes results_all.csv).
"""
from __future__ import annotations

import csv
import logging
import sys
from pathlib import Path

import numpy as np
from tqdm import tqdm

root = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root))

from audio.audio_library import get_audio, list_audio_ids
from audio.fft_analysis import compute_fft
from mapping.spectral_mapping import map_fft_to_coefficients
from analysis.scalar_field import compute_scalar_field
from analysis.nodal_surface import compute_topology_metrics
from analysis.symmetry import compute_symmetry

EIGEN_DIR = root / "data" / "eigen"
RESULTS_DIR = root / "data" / "results"
RESULTS_CSV = RESULTS_DIR / "results.csv"
RESULTS_ALL_CSV = RESULTS_DIR / "results_all.csv"
N_EIGEN = 50
STRATEGIES = ["direct", "mel", "energy"]

# The nine meshes reported in the paper, in the order they appear there.
PAPER_MESHES = [
    "sphere",
    "torus",
    "double_torus",
    "cube",
    "tetrahedron",
    "octahedron",
    "icosahedron",
    "ellipsoid",
    "flat_plate",
]

logging.basicConfig(level=logging.INFO, format="[%(asctime)s] %(levelname)s %(message)s", datefmt="%H:%M:%S", stream=sys.stderr)
log = logging.getLogger(__name__)


def list_available_meshes():
    if not EIGEN_DIR.exists():
        return []
    return sorted([p.stem for p in EIGEN_DIR.glob("*.npz")])


def list_paper_meshes():
    """The pinned nine. Missing eigenbases are an error, not a smaller table."""
    missing = [m for m in PAPER_MESHES
               if not (EIGEN_DIR / f"{m}.npz").exists()
               and not (EIGEN_DIR / f"{m}.json").exists()]
    if missing:
        log.error("Missing eigenbasis (.npz or .json) for %s. Run step1.sh first.",
                  ", ".join(missing))
        sys.exit(1)
    return list(PAPER_MESHES)


def load_eigen(mesh_name):
    """Load a mesh eigenbasis, preferring .npz and falling back to the committed
    .json. The nine paper meshes ship only as .json (the .npz is git-ignored and
    regenerated by step1), so a fresh clone reproduces this table from the .json."""
    npz = EIGEN_DIR / f"{mesh_name}.npz"
    if npz.exists():
        d = np.load(npz, allow_pickle=True)
        evals = d["eigenvalues"] if "eigenvalues" in d.files else None
        return d["vertices"], d["faces"], d["eigenvectors"], evals
    js = EIGEN_DIR / f"{mesh_name}.json"
    if js.exists():
        import json as _json
        log.warning("%s: using float32 .json (approximate); .npz gives the paper's "
                    "float64 values. Run step1.sh to regenerate .npz.", mesh_name)
        d = _json.loads(js.read_text())
        return (np.asarray(d["vertices"]), np.asarray(d["faces"]),
                np.asarray(d["eigenvectors"]), np.asarray(d["eigenvalues"]))
    raise FileNotFoundError(f"No eigenbasis for {mesh_name} (.npz or .json) in {EIGEN_DIR}")


def run_one(mesh_name, audio_id, strategy):
    V, F, evecs, evals = load_eigen(mesh_name)
    sig, sr = get_audio(audio_id)
    mag, _ = compute_fft(sig, sr)
    coef = map_fft_to_coefficients(mag, N_EIGEN, strategy=strategy, eigenvalues=evals)
    f = compute_scalar_field(evecs, coef)
    m = compute_topology_metrics(V, F, f)
    S = compute_symmetry(V, f)
    return {"beta0": m.beta0, "beta1": m.beta1, "chi": m.chi, "A_ratio": m.A_ratio, "S": S}


def main():
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    run_all_meshes = "--all" in sys.argv[1:]
    if run_all_meshes:
        meshes = list_available_meshes()
        out_csv = RESULTS_ALL_CSV
        if not meshes:
            log.error("data/eigen/*.npz missing. Run step1.sh first.")
            sys.exit(1)
    else:
        meshes = list_paper_meshes()
        out_csv = RESULTS_CSV
    audio_ids = list_audio_ids()
    rows = []
    total = len(meshes) * len(audio_ids) * len(STRATEGIES)
    with tqdm(total=total, desc="experiment", unit="run") as pbar:
        for mesh_name in meshes:
            for audio_id in audio_ids:
                for strategy in STRATEGIES:
                    try:
                        r = run_one(mesh_name, audio_id, strategy)
                        rows.append({
                            "mesh": mesh_name, "audio": audio_id, "strategy": strategy,
                            **r,
                        })
                    except Exception as e:
                        log.exception("%s %s %s: %s", mesh_name, audio_id, strategy, e)
                        raise
                    pbar.update(1)
    fieldnames = ["mesh", "audio", "strategy", "beta0", "beta1", "chi", "A_ratio", "S"]
    with open(out_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)
    log.info("Saved %s: %d rows (%d meshes)", out_csv.name, len(rows), len(meshes))
    print("Step 4 run_all done.", file=sys.stderr)


if __name__ == "__main__":
    main()
